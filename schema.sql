-- R1: acesso por pessoa. E-mail unico, senha guardada como hash.
CREATE TABLE usuarios (
  usuario_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       TEXT NOT NULL,
  email      TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  criado_em  DATE NOT NULL DEFAULT CURRENT_DATE,
  -- So admin gerencia usuarios no painel (ver admin.sql).
  admin      BOOLEAN NOT NULL DEFAULT FALSE
);

-- R2: toda conta tem um unico dono e nasce com saldo inicial informado (nunca nulo).
-- O UNIQUE (conta_id, usuario_id) existe para permitir as chaves estrangeiras compostas (R8).
-- R5: o saldo atual NAO e guardado; ver a view saldo_contas.
CREATE TABLE contas (
  conta_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id    INTEGER NOT NULL REFERENCES usuarios (usuario_id),
  nome          TEXT NOT NULL,
  tipo          TEXT NOT NULL CHECK (tipo IN ('corrente', 'cartao', 'especie', 'poupanca')),
  saldo_inicial NUMERIC(10,2) NOT NULL,
  data_abertura DATE NOT NULL,
  UNIQUE (usuario_id, nome),
  UNIQUE (conta_id, usuario_id)
);

-- R3: categorias da pessoa; nome unico por pessoa, cor no formato #RRGGBB.
-- R9: "ativa" permite aposentar uma categoria sem apagar historico.
CREATE TABLE categorias (
  categoria_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id   INTEGER NOT NULL REFERENCES usuarios (usuario_id),
  nome         TEXT NOT NULL,
  tipo         TEXT NOT NULL CHECK (tipo IN ('entrada', 'saida')),
  cor_hex      TEXT NOT NULL CHECK (cor_hex ~ '^#[0-9A-Fa-f]{6}$'),
  ativa        BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (usuario_id, nome),
  UNIQUE (categoria_id, usuario_id)
);

-- R6: gastos que repetem todo mes. dia_do_mes 1..28 cabe em qualquer mes.
CREATE TABLE recorrencias (
  recorrencia_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id     INTEGER NOT NULL REFERENCES usuarios (usuario_id),
  conta_id       INTEGER NOT NULL,
  categoria_id   INTEGER NOT NULL,
  descricao      TEXT NOT NULL,
  valor_previsto NUMERIC(10,2) NOT NULL CHECK (valor_previsto > 0),
  dia_do_mes     INTEGER NOT NULL CHECK (dia_do_mes BETWEEN 1 AND 28),
  data_inicio    DATE NOT NULL,
  data_fim       DATE,
  CHECK (data_fim IS NULL OR data_fim >= data_inicio),
  FOREIGN KEY (conta_id, usuario_id)     REFERENCES contas (conta_id, usuario_id),
  FOREIGN KEY (categoria_id, usuario_id) REFERENCES categorias (categoria_id, usuario_id)
);

-- R4, R7, R8, R9, R10.
-- valor sempre positivo; quem diz se entrou ou saiu e o tipo.
-- R8: as FKs compostas obrigam conta e categoria a terem o mesmo dono do lancamento.
-- R9: sem ON DELETE CASCADE: apagar categoria ou conta usada e bloqueado (RESTRICT implicito).
-- R7: recorrencia_id nulo = lancamento avulso.
CREATE TABLE lancamentos (
  lancamento_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      INTEGER NOT NULL REFERENCES usuarios (usuario_id),
  conta_id        INTEGER NOT NULL,
  categoria_id    INTEGER NOT NULL,
  recorrencia_id  INTEGER REFERENCES recorrencias (recorrencia_id),
  tipo            TEXT NOT NULL CHECK (tipo IN ('entrada', 'saida')),
  valor           NUMERIC(10,2) NOT NULL CHECK (valor > 0),
  data_lancamento DATE NOT NULL,
  descricao       TEXT,
  FOREIGN KEY (conta_id, usuario_id)     REFERENCES contas (conta_id, usuario_id),
  FOREIGN KEY (categoria_id, usuario_id) REFERENCES categorias (categoria_id, usuario_id)
);

-- R11: indices para as consultas mais frequentes.
-- "lancamentos de uma pessoa num mes"
CREATE INDEX idx_lancamentos_usuario_data ON lancamentos (usuario_id, data_lancamento);
-- "total por categoria no periodo"
CREATE INDEX idx_lancamentos_usuario_categoria_data ON lancamentos (usuario_id, categoria_id, data_lancamento);
-- saldo por conta e as FKs compostas
CREATE INDEX idx_lancamentos_conta ON lancamentos (conta_id);
-- origem por recorrencia (so os que tem origem)
CREATE INDEX idx_lancamentos_recorrencia ON lancamentos (recorrencia_id) WHERE recorrencia_id IS NOT NULL;

-- R5: saldo calculado na hora = saldo inicial + entradas - saidas.
-- Calcular evita um numero duplicado que poderia divergir dos lancamentos.
CREATE VIEW saldo_contas AS
SELECT c.conta_id,
       c.usuario_id,
       c.nome,
       c.saldo_inicial
         + COALESCE(SUM(CASE WHEN l.tipo = 'entrada' THEN l.valor ELSE -l.valor END), 0) AS saldo_atual
FROM contas c
LEFT JOIN lancamentos l ON l.conta_id = c.conta_id
GROUP BY c.conta_id, c.usuario_id, c.nome, c.saldo_inicial;

